const CASE_TIMELINE_ARTIFACT_RELATIVE_SET = new Set(CASE_TIMELINE_ARTIFACT_RELATIVE_CANDIDATES);
const CASE_TIMELINE_READ_MODEL_RELATIVE_SET = new Set(CASE_TIMELINE_READ_MODEL_RELATIVE_CANDIDATES);
const CASE_TIMELINE_CANONICAL_ARTIFACT_RELATIVE_SET = new Set(CASE_TIMELINE_ARTIFACT_RELATIVES);

export function normalizeMatterArtifactRelativePath(value = "") {
  return String(value || "").replaceAll("\\", "/").replace(/^\/+/, "");
}

export function isCaseTimelineArtifactPath(value = "") {
  return CASE_TIMELINE_ARTIFACT_RELATIVE_SET.has(normalizeMatterArtifactRelativePath(value));
}

export function isCanonicalCaseTimelineArtifactPath(value = "") {
  return CASE_TIMELINE_CANONICAL_ARTIFACT_RELATIVE_SET.has(normalizeMatterArtifactRelativePath(value));
}

export function isCaseTimelineReadModelPath(value = "") {
  return CASE_TIMELINE_READ_MODEL_RELATIVE_SET.has(normalizeMatterArtifactRelativePath(value));
}

