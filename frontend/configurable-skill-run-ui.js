import { escapeHtml } from "./dom-utils.js";
import { formatConfigurableRunOutputDocumentState } from "./configurable-skill-run-labels.js";

export function getConfigurableRunArtifactPath(result = {}) {
  const runRecord = result.runRecord || {};
  return result.outputPaths?.markdown || result.outputPath || runRecord.outputPaths?.markdown || "";
}

export function buildConfigurableRunPending(result = {}) {
  const skill = result.skill || {};
  const runRecord = result.runRecord || {};
  const slash = skill.slash || runRecord.slash || "";
  return {
    phase: "action_sheet",
    slash,
    title: skill.title || runRecord.title || slash || "Custom Skill",
    artifactPath: getConfigurableRunArtifactPath(result),
    skill,
    runRecord,
    result,
  };
}

export function renderConfigurableSkillRunOutput(result = {}) {
  const skill = result.skill || {};
  const runRecord = result.runRecord || {};
  const overwrite = runRecord.overwrite || "not_needed";
  return `
      <h1>${escapeHtml(skill.title || "Custom Skill Result")}</h1>
      <p class="muted">Generated by <code>${escapeHtml(skill.slash || "")}</code>. Review before relying on it.</p>
      <section class="skill-router-result">
        <dl class="skill-card-meta">
          <div><dt>Run</dt><dd>${escapeHtml(runRecord.id || result.runId || "Not recorded")}</dd></div>
          <div><dt>Matter</dt><dd>${escapeHtml(runRecord.matterName || runRecord.matterFolder || result.matter?.matterName || result.matter?.matter_name || "Unknown matter")}</dd></div>
          <div><dt>Provider</dt><dd>${escapeHtml(formatConfigurableRunProvider(result))}</dd></div>
          <div><dt>Output</dt><dd><code>${escapeHtml(getConfigurableRunArtifactPath(result))}</code></dd></div>
          <div><dt>Metadata</dt><dd><code>${escapeHtml(result.outputPaths?.json || "")}</code></dd></div>
          <div><dt>Output document</dt><dd>${escapeHtml(formatConfigurableRunOutputDocumentState(overwrite))}</dd></div>
        </dl>
        <pre class="skill-sample-markdown">${escapeHtml(result.markdown || "")}</pre>
      </section>
    `;
}

